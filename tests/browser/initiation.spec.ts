import { test, expect, type APIRequestContext } from "@playwright/test";
const origin = "http://localhost:3100";
const workspace = async (api: APIRequestContext) => (await api.get("/api/workspace")).json();
const write = (api: APIRequestContext, path: string, data: object, method = "POST") => api.fetch(path, { method, data, headers: { Origin: origin } });

test("project initiation has the new labels, seven phases, multi-selection and no milestone or publication section", async ({ page, browser }) => {
  await page.goto("/projects");
  const contexts = [await browser.newContext(), await browser.newContext()];
  for (const [index, context] of contexts.entries()) {
    await context.request.post(`${origin}/api/demo`, { form: { view: "new" }, headers: { Origin: origin } });
    expect((await write(context.request, `${origin}/api/onboarding`, { name: `Initiation member ${index + 1}`, projectIds: [] })).ok()).toBeTruthy();
  }
  await page.reload();
  await page.getByRole("button", { name: "New project", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("Project goal");
  await expect(dialog).toContainText("Project phase");
  await expect(dialog.getByLabel("Methods", { exact: true })).toBeVisible();
  await expect(dialog.getByLabel("Current phase").locator("option")).toHaveText(["Not set", "Ideation", "Design", "Alpha prototype", "Alpha prototype testing", "Beta prototype", "Beta prototype testing", "In use"]);
  await expect(dialog.getByRole("heading", { name: "Next milestone" })).toHaveCount(0);
  await expect(dialog.getByText("Publication details", { exact: true })).toHaveCount(0);
  await dialog.getByLabel("Project name", { exact: true }).fill("Initiation browser project");
  await dialog.getByLabel("Goal", { exact: true }).fill("Validate the requested workflow");
  await dialog.getByLabel("Current phase").selectOption("Design");
  const members = dialog.getByRole("group", { name: /Project members/ });
  await members.getByRole("checkbox", { name: /Initiation member 1/ }).check();
  await members.getByRole("checkbox", { name: /Initiation member 2/ }).check();
  const supervisors = dialog.getByRole("group", { name: /Supervisors/ });
  await supervisors.getByRole("checkbox", { name: /Initiation member 1/ }).check();
  await supervisors.getByRole("checkbox", { name: /Initiation member 2/ }).check();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/ve-initiation-mobile.png", fullPage: true });
  await dialog.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const data = await workspace(page.request), project = data.projects.find((p: { name: string }) => p.name === "Initiation browser project");
  expect(project.phase).toBe("Design"); expect(project.milestone).toBe(""); expect(project.publicationStatus).toBe("");
  expect(data.memberships.filter((m: { projectId: string; supervisor: boolean }) => m.projectId === project.id && m.supervisor)).toHaveLength(2);
  await page.goto("/"); await expect(page.getByRole("region", { name: "Admin dashboard" })).toContainText("Initiation browser project");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "/tmp/ve-admin-dashboard-mobile.png", fullPage: true });
  for (const context of contexts) await context.close();
});

test("invite a new member, let them fill their profile, and request initiation and task forms", async ({ page, browser }) => {
  test.setTimeout(120000);
  await page.goto("/projects");
  const projectId = crypto.randomUUID();
  expect((await write(page.request, "/api/projects", { id: projectId, name: "Invited collaboration project", goal: "Delegate forms" })).ok()).toBeTruthy();
  const before = await workspace(page.request);
  await page.goto(`/projects/${projectId}`);
  await page.getByRole("tab", { name: "People", exact: true }).click();
  await page.getByRole("button", { name: "Invite new member", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("Member’s Google email").fill("member@demo.invalid");
  await dialog.getByRole("button", { name: "Create invitation", exact: true }).click();
  await expect(dialog.getByLabel("Invitation link")).toBeVisible();
  const url = await dialog.getByLabel("Invitation link").inputValue();
  expect((await workspace(page.request)).people).toHaveLength(before.people.length);
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await page.goto(url); await expect(page.getByRole("heading", { name: "This invitation is unavailable" })).toBeVisible();
  const context = await browser.newContext(), member = await context.newPage();
  await member.request.post(`${origin}/api/demo`, { form: { view: "member" }, headers: { Origin: origin } });
  await member.goto(url);
  await member.getByRole("button", { name: "Accept and complete my profile" }).click();
  await expect(member).toHaveURL(/\/account$/);
  await member.getByLabel("Your name", { exact: true }).fill("Invited researcher");
  await member.getByLabel("About you", { exact: true }).fill("I work on prototypes.");
  await member.getByRole("button", { name: "Save account", exact: true }).click();
  await expect(member.getByRole("status")).toContainText("Account saved");
  expect((await workspace(member.request)).logins).toEqual([]);
  await page.goto(`/projects/${projectId}`);
  async function requestForm(kind: string) {
    await page.getByRole("button", { name: "Request a form", exact: true }).click();
    const form = page.getByRole("dialog");
    await form.getByLabel("Form", { exact: true }).selectOption(kind);
    await form.getByRole("checkbox", { name: /Invited researcher/ }).check();
    await form.getByRole("button", { name: "Send request", exact: true }).click();
    await expect(form).toHaveCount(0);
  }
  await requestForm("initiation");
  await member.goto("/"); await expect(member.getByRole("heading", { name: "Requests for you" })).toBeVisible();
  await member.getByRole("link", { name: "Open request →" }).click();
  await member.getByRole("button", { name: "Open initiation form", exact: true }).click();
  dialog = member.getByRole("dialog");
  await expect(dialog.getByText("Publication details", { exact: true })).toHaveCount(0);
  await dialog.getByLabel("Goal", { exact: true }).fill("The invited member completed initiation");
  await dialog.getByRole("button", { name: "Save project", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.reload(); await expect(page.getByRole("region", { name: "Project form requests" })).toContainText("Completed");
  await requestForm("task");
  await member.reload(); await member.getByRole("button", { name: "Open task form", exact: true }).click();
  dialog = member.getByRole("dialog");
  await dialog.getByLabel("Responsibility", { exact: true }).fill("Build invited prototype");
  await dialog.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const final = await workspace(page.request), project = final.projects.find((p: { id: string }) => p.id === projectId);
  expect(project.formRequests.every((r: { completedAt: string }) => r.completedAt)).toBeTruthy();
  expect(project.workstreams[0].name).toBe("Build invited prototype");
  await page.goto("/"); await expect(page.getByRole("region", { name: "Admin dashboard" })).toContainText("Invited researcher");
  await page.screenshot({ path: "/tmp/ve-admin-dashboard-desktop.png", fullPage: true });
  await context.close();
});
